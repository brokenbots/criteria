//
// Delivery semantics:
//   - At-least-once delivery. Consumers dedup on (peer conn identity,
//     event_seq).
//   - event_seq is global monotonic per peer process and gapless.
//   - Replay: a host (re-)opening Supervise passes since_event_seq; the peer
//     streams lifecycle truth strictly after that value (exclusive).
//   - Terminal events (ProcessExited, CrashClassified) persist to a bounded
//     in-peer journal (default 4096 events, env-tunable) and are replayed
//     FIRST on reconnect, so crash evidence survives the RPC stream that
//     died.
//
// Ordering:
//   - Journal append order == emission order.
//   - StreamFlushed.up_to_seq is monotonic per channel.
//
